use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use walkdir::WalkDir;

use crate::config::VaultConfig;
use crate::error::{Result, StoreError};
use crate::frontmatter::Resource;
use crate::fsutil::{read_to_string, write_atomic};
use crate::generated::{LogEntry, render_index, render_log};
use crate::page::{Context, Issue, Page};
use crate::page_id::PageId;
use crate::raw::{RawEntry, RawStore};

/// A vault on disk: `wiki/` (the OKF bundle), `raw/`, `journal/`, `edda.toml` and the rebuildable `.edda/`.
#[derive(Debug, Clone)]
pub struct Vault {
    root: PathBuf,
    config: VaultConfig,
}

impl Vault {
    /// Opens the vault at `root`, which must contain `wiki/`.
    pub fn open(root: impl Into<PathBuf>) -> Result<Self> {
        let root = root.into();
        if !root.join("wiki").is_dir() {
            return Err(StoreError::NotAVault(root));
        }
        let config = VaultConfig::load(&root.join("edda.toml"))?;
        Ok(Self { root, config })
    }

    pub fn root(&self) -> &Path {
        &self.root
    }

    pub fn config(&self) -> &VaultConfig {
        &self.config
    }

    pub fn wiki_dir(&self) -> PathBuf {
        self.root.join("wiki")
    }

    pub fn journal_dir(&self) -> PathBuf {
        self.root.join("journal")
    }

    /// Where the search index and link graph live. Deleting it loses nothing.
    pub fn index_dir(&self) -> PathBuf {
        self.root.join(".edda").join("index")
    }

    pub fn raw(&self) -> RawStore {
        RawStore::new(self.root.join("raw"))
    }

    /// Every page in the bundle, sorted, without the generated `index.md` and `log.md`.
    pub fn page_ids(&self) -> Result<Vec<PageId>> {
        let wiki = self.wiki_dir();
        let mut ids = Vec::new();
        let walk = WalkDir::new(&wiki)
            .min_depth(1)
            .into_iter()
            .filter_entry(|e| !e.file_name().to_string_lossy().starts_with('.'));
        for entry in walk {
            let entry = entry.map_err(|e| {
                let path = e.path().map_or_else(|| wiki.clone(), Path::to_path_buf);
                StoreError::io(path, e.into())
            })?;
            if !entry.file_type().is_file() {
                continue;
            }
            let relative = entry.path().strip_prefix(&wiki).unwrap_or(entry.path());
            if let Some(id) = PageId::from_relative(relative).filter(|id| !id.is_generated()) {
                ids.push(id);
            }
        }
        ids.sort();
        Ok(ids)
    }

    pub fn page_exists(&self, id: &PageId) -> bool {
        !id.is_generated() && id.to_path(&self.wiki_dir()).is_file()
    }

    pub fn read_page(&self, id: &PageId) -> Result<Page> {
        let path = id.to_path(&self.wiki_dir());
        if !path.is_file() {
            return Err(StoreError::PageNotFound(id.to_string()));
        }
        Page::parse(id.clone(), &read_to_string(&path)?)
    }

    /// Every page, in id order.
    pub fn pages(&self) -> Result<Vec<Page>> {
        self.page_ids()?
            .iter()
            .map(|id| self.read_page(id))
            .collect()
    }

    pub fn write_page(&self, page: &Page) -> Result<()> {
        if page.id.is_generated() {
            return Err(StoreError::InvalidPageId {
                id: page.id.to_string(),
                reason: "generated by the kernel",
            });
        }
        write_atomic(
            &page.id.to_path(&self.wiki_dir()),
            page.to_markdown()?.as_bytes(),
        )
    }

    /// Regenerates `index.md` from the pages.
    pub fn write_index(&self) -> Result<()> {
        let index = render_index(&self.config.title, &self.pages()?);
        write_atomic(&self.wiki_dir().join("index.md"), index.as_bytes())
    }

    /// Regenerates `log.md` from journal entries.
    pub fn write_log(&self, entries: &[LogEntry]) -> Result<()> {
        write_atomic(
            &self.wiki_dir().join("log.md"),
            render_log(entries).as_bytes(),
        )
    }

    /// Checks a page against the kernel's rules, in the context of this vault's pages and sources.
    pub fn check(&self, page: &Page) -> Result<Vec<Issue>> {
        Ok(page.check(&self.snapshot()?))
    }

    /// The pages and sources as they are now, for checking many pages without rereading the disk.
    pub fn snapshot(&self) -> Result<Snapshot<'_>> {
        Ok(Snapshot {
            config: &self.config,
            pages: self.page_ids()?.into_iter().collect(),
            raw: self.raw().list()?,
        })
    }
}

/// The vault's page ids and raw sources at one moment.
#[derive(Debug)]
pub struct Snapshot<'a> {
    config: &'a VaultConfig,
    pages: BTreeSet<PageId>,
    raw: Vec<RawEntry>,
}

impl Snapshot<'_> {
    /// Counts a page that does not exist yet, so a proposal's links to the page it creates are not broken.
    pub fn add_page(&mut self, id: PageId) {
        self.pages.insert(id);
    }
}

impl Context for Snapshot<'_> {
    fn allowed_type(&self, kind: &str) -> bool {
        self.config.types.iter().any(|t| t == kind)
    }

    fn page_exists(&self, id: &PageId) -> bool {
        self.pages.contains(id)
    }

    fn source_resolves(&self, resource: &Resource) -> bool {
        match resource {
            Resource::Raw(prefix) => {
                let prefix = prefix.to_ascii_lowercase();
                !prefix.is_empty()
                    && self
                        .raw
                        .iter()
                        .filter(|e| e.hash.starts_with(&prefix))
                        .count()
                        == 1
            }
            Resource::Url(url) => self.raw.iter().any(|e| e.meta.url.as_deref() == Some(url)),
        }
    }
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::*;
    use crate::raw::RawMeta;

    fn vault() -> (tempfile::TempDir, Vault) {
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir_all(dir.path().join("wiki/people/.drafts")).unwrap();
        fs::write(dir.path().join("wiki/people/.drafts/x.md"), "hidden").unwrap();
        fs::write(dir.path().join("wiki/notes.txt"), "not a page").unwrap();
        let vault = Vault::open(dir.path()).unwrap();
        (dir, vault)
    }

    fn page(id: &str, text: &str) -> Page {
        Page::parse(PageId::new(id).unwrap(), text).unwrap()
    }

    #[test]
    fn refuses_a_folder_without_a_bundle() {
        let dir = tempfile::tempdir().unwrap();
        assert!(matches!(
            Vault::open(dir.path()),
            Err(StoreError::NotAVault(_))
        ));
    }

    #[test]
    fn writes_reads_and_lists_pages() {
        let (_dir, vault) = vault();
        assert!(vault.pages().unwrap().is_empty());
        let ada = page(
            "people/ada.md",
            "---\ntype: Person\ntitle: Ada\ndescription: d\n---\nSee [T](/t.md).\n",
        );
        vault.write_page(&ada).unwrap();
        vault
            .write_page(&page(
                "t.md",
                "---\ntype: Concept\ntitle: T\ndescription: d\n---\nBody\n",
            ))
            .unwrap();
        vault.write_index().unwrap();
        vault.write_log(&[]).unwrap();
        let ids: Vec<_> = vault
            .page_ids()
            .unwrap()
            .into_iter()
            .map(|id| id.to_string())
            .collect();
        assert_eq!(ids, ["people/ada.md", "t.md"]);
        assert_eq!(vault.read_page(&ada.id).unwrap(), ada);
        assert!(vault.page_exists(&ada.id));
        assert!(!vault.page_exists(&PageId::new("index.md").unwrap()));
        let index = fs::read_to_string(vault.wiki_dir().join("index.md")).unwrap();
        assert!(index.contains("okf_version: \"0.2\""));
        assert!(index.contains("- [Ada](/people/ada.md): d"));
        assert!(vault.check(&ada).unwrap().is_empty());
        assert!(matches!(
            vault.read_page(&PageId::new("gone.md").unwrap()),
            Err(StoreError::PageNotFound(_))
        ));
        assert!(vault.write_page(&page("index.md", "---\n---\n")).is_err());
        assert_eq!(vault.config().title, "Edda vault");
        assert!(vault.index_dir().ends_with(".edda/index"));
        assert!(vault.journal_dir().ends_with("journal"));
        assert_eq!(vault.root(), _dir.path());
    }

    #[test]
    fn checks_sources_against_raw() {
        let (_dir, vault) = vault();
        let entry = vault
            .raw()
            .add(
                b"notes",
                Some("md"),
                &RawMeta {
                    url: Some("https://x.example".into()),
                    ..RawMeta::default()
                },
            )
            .unwrap();
        let text = format!(
            "---\ntype: Concept\ntitle: A\ndescription: d\nsources:\n  - id: u\n    resource: https://x.example\n  \
             - id: r\n    resource: raw:{}\n  - id: e\n    resource: \"raw:\"\n---\nA.[^u][^r][^e]\n\n[^u]: a\n[^r]: b\n[^e]: c\n",
            &entry.hash[..6]
        );
        let issues = vault.check(&page("a.md", &text)).unwrap();
        assert_eq!(
            issues,
            [Issue::UnresolvedSource {
                id: "e".into(),
                resource: "raw:".into()
            }]
        );
    }
}
